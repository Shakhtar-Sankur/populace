// Turn Natural Earth's land outline into one SVG path, projected to the map's
// own viewBox, and write it into the renderer as a plain script.
//
//   node build/make-world.mjs
//
// Done at build time on purpose. The window runs under `default-src 'none'`,
// so it cannot fetch a map at runtime and should not want to: a testing tool
// that phones out for tiles is a tool that fails offline and leaks which
// machine ran it. The geometry is Natural Earth via the world-atlas package,
// which is public domain.
//
// 50m rather than 110m: at sixteen times zoom the coarse outline is visibly
// blocky, and this is a desktop application where a few hundred kilobytes of
// geometry costs nothing.
//
// TopoJSON is decoded here rather than with a library. It is a delta-encoded
// arc list and about forty lines to walk, which is less code than the
// dependency would add, and this file then explains the format to whoever
// reads it next.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const studio = path.join(here, "..");
const source = path.join(studio, "node_modules", "world-atlas", "land-50m.json");
const out = path.join(studio, "renderer", "world.js");

// Must match the projection in app.js. Antarctica and the high Arctic are
// cropped: nobody is being simulated there, and including them spends half the
// panel's height on empty white.
const W = 720, H = 320, LAT_MAX = 78, LAT_MIN = -58;
const projX = (lng) => ((lng + 180) / 360) * W;
const projY = (lat) => ((LAT_MAX - lat) / (LAT_MAX - LAT_MIN)) * H;

const topo = JSON.parse(fs.readFileSync(source, "utf8"));
const { scale: [sx, sy], translate: [tx, ty] } = topo.transform;

/** One arc, delta-decoded and turned into [lng, lat] pairs. */
function decodeArc(arc) {
  let x = 0, y = 0;
  return arc.map(([dx, dy]) => {
    x += dx; y += dy;
    return [x * sx + tx, y * sy + ty];
  });
}
const arcs = topo.arcs.map(decodeArc);

/** A negative index means that arc traversed backwards, encoded as ~i. */
function ring(indices) {
  const points = [];
  for (const i of indices) {
    const arc = i < 0 ? [...arcs[~i]].reverse() : arcs[i];
    // Consecutive arcs share an endpoint; keeping both would double the point.
    points.push(...(points.length ? arc.slice(1) : arc));
  }
  return points;
}

const round = (n) => Math.round(n * 10) / 10;   // 0.1px is finer than the screen

const pieces = [];
for (const geometry of topo.objects.land.geometries) {
  const polygons = geometry.type === "MultiPolygon" ? geometry.arcs : [geometry.arcs];
  for (const polygon of polygons) {
    for (const indices of polygon) {
      const points = ring(indices);
      if (points.length < 4) continue;   // a speck at this resolution
      const d = points
        .map(([lng, lat], i) => `${i ? "L" : "M"}${round(projX(lng))} ${round(projY(lat))}`)
        .join("");
      pieces.push(`${d}Z`);
    }
  }
}

const body = `// Generated by build/make-world.mjs - do not edit.
// Natural Earth land outline (public domain), projected to ${W}x${H},
// latitudes ${LAT_MIN} to ${LAT_MAX}.
const WORLD_PATH = ${JSON.stringify(pieces.join(""))};
const WORLD_VIEW = { w: ${W}, h: ${H}, latMax: ${LAT_MAX}, latMin: ${LAT_MIN} };
`;

fs.writeFileSync(out, body);
console.log(`world.js — ${pieces.length} rings, ${(body.length / 1024).toFixed(0)} KB`);
