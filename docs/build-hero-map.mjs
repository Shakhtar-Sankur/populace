// Generates the world map behind the hero.
//
//   node docs/build-hero-map.mjs
//
// The same Natural Earth geometry and the same equirectangular projection the
// application itself draws, so the map on the landing page is not an
// illustration of the product - it is the product's own map, with the
// twenty-five cities of a real run on it.
//
// 110m rather than the application's 50m: this is a background at a tenth of
// full opacity behind a headline, nobody zooms into it, and a landing page
// should not carry 650 KB of coastline to make a point.
//
// Written to docs/hero-map.js as one path string plus the city list.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.join(here, "..", "studio", "node_modules", "world-atlas", "land-110m.json");

if (!fs.existsSync(source)) {
  console.error(`No world-atlas data at ${source}.\nRun: npm install --save-dev world-atlas   (in studio/)`);
  process.exit(1);
}

// Matches the application's projection, cropped the same way: nobody is
// simulated in Antarctica, and it would take a third of the height.
const W = 1200, H = 520, LAT_MAX = 78, LAT_MIN = -58;
const projX = (lng) => ((lng + 180) / 360) * W;
const projY = (lat) => ((LAT_MAX - lat) / (LAT_MAX - LAT_MIN)) * H;

const topo = JSON.parse(fs.readFileSync(source, "utf8"));
const { scale: [sx, sy], translate: [tx, ty] } = topo.transform;

const arcs = topo.arcs.map((arc) => {
  let x = 0, y = 0;
  return arc.map(([dx, dy]) => {
    x += dx; y += dy;
    return [x * sx + tx, y * sy + ty];
  });
});

/** Negative index means that arc backwards, encoded as ~i. */
function ring(indices) {
  const points = [];
  for (const i of indices) {
    const arc = i < 0 ? [...arcs[~i]].reverse() : arcs[i];
    points.push(...(points.length ? arc.slice(1) : arc));
  }
  return points;
}

const round = (n) => Math.round(n * 10) / 10;
const pieces = [];
for (const geometry of topo.objects.land.geometries) {
  const polygons = geometry.type === "MultiPolygon" ? geometry.arcs : [geometry.arcs];
  for (const polygon of polygons) {
    for (const indices of polygon) {
      const pts = ring(indices);
      if (pts.length < 4) continue;
      pieces.push(pts.map(([lng, lat], i) =>
        `${i ? "L" : "M"}${round(projX(lng))} ${round(projY(lat))}`).join("") + "Z");
    }
  }
}

// The twenty-five cities of the 200-driver run on 23 August 2026, projected
// once here so the page does no trigonometry.
const CITIES = [
  ["Manila", 14.5995, 120.9842], ["Mumbai", 19.076, 72.8777], ["Delhi", 28.6139, 77.209],
  ["Jakarta", -6.2088, 106.8456], ["São Paulo", -23.5505, -46.6333], ["Mexico City", 19.4326, -99.1332],
  ["Bogotá", 4.711, -74.0721], ["Lima", -12.0464, -77.0428], ["Lagos", 6.5244, 3.3792],
  ["Nairobi", -1.2921, 36.8219], ["Accra", 5.6037, -0.187], ["Cairo", 30.0444, 31.2357],
  ["Johannesburg", -26.2041, 28.0473], ["Istanbul", 41.0082, 28.9784], ["Dubai", 25.2048, 55.2708],
  ["Riyadh", 24.7136, 46.6753], ["Moscow", 55.7558, 37.6173], ["Kyiv", 50.4501, 30.5234],
  ["Warsaw", 52.2297, 21.0122], ["Madrid", 40.4168, -3.7038], ["Almaty", 43.222, 76.8512],
  ["Tashkent", 41.2995, 69.2401], ["Baku", 40.4093, 49.8671], ["Casablanca", 33.5731, -7.5898],
  ["Amman", 31.9454, 35.9284],
];

const dots = CITIES.map(([name, lat, lng]) => ({
  n: name, x: round(projX(lng)), y: round(projY(lat)),
}));

const body = `// Generated by docs/build-hero-map.mjs — do not edit.
// Natural Earth land outline (public domain), projected to ${W}x${H}, the same
// projection the application draws. Cities are the twenty-five of the
// 200-driver run on 23 August 2026.
window.HERO_MAP = {
  w: ${W}, h: ${H},
  path: ${JSON.stringify(pieces.join(""))},
  cities: ${JSON.stringify(dots)}
};
`;

const out = path.join(here, "hero-map.js");
fs.writeFileSync(out, body);
console.log(`hero-map.js — ${pieces.length} rings, ${dots.length} cities, ${(body.length / 1024).toFixed(0)} KB`);
